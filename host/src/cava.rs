//! Runs `cava` with raw binary output and hands every frame to a callback.

use std::fs;
use std::io::{self, Read};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

use crate::config::{config_dir, Config};

/// Kills the cava child process when dropped (no orphan cava left behind).
struct CavaProc {
    child: Child,
}

impl Drop for CavaProc {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

fn write_cava_config(cfg: &Config, input: &str) -> io::Result<std::path::PathBuf> {
    let path = config_dir().join("cava.conf");
    let conf = format!(
        "# generated by aksara-hud, edits are overwritten\n\
         [general]\nbars = {bars}\nframerate = {fps}\nautosens = 1\n\n\
         [input]\nmethod = {input}\nsource = auto\n\n\
         [output]\nmethod = raw\nraw_target = /dev/stdout\ndata_format = binary\nbit_format = 8bit\nchannels = mono\n\n\
         [smoothing]\nnoise_reduction = 77\n",
        bars = cfg.cava_bars,
        fps = cfg.cava_fps,
    );
    fs::create_dir_all(config_dir())?;
    fs::write(&path, conf)?;
    Ok(path)
}

/// One cava run. Returns Ok(true) if `on_frame` asked to stop,
/// Err(message incl. cava's stderr) if cava died.
fn run_once(cfg: &Config, input: &str, on_frame: &mut impl FnMut(&[u8]) -> bool) -> Result<bool, String> {
    let conf = write_cava_config(cfg, input).map_err(|e| e.to_string())?;
    let mut child = Command::new("cava")
        .arg("-p")
        .arg(&conf)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("tidak bisa menjalankan cava: {e}"))?;
    let mut out = child.stdout.take().expect("piped stdout");
    let mut err = child.stderr.take().expect("piped stderr");
    let _guard = CavaProc { child };
    let mut frame = vec![0u8; cfg.cava_bars];
    loop {
        if out.read_exact(&mut frame).is_err() {
            let mut msg = String::new();
            let _ = err.read_to_string(&mut msg);
            let msg = msg.trim();
            return Err(if msg.is_empty() { "cava keluar tanpa pesan".into() } else { msg.to_string() });
        }
        if !on_frame(&frame) {
            return Ok(true);
        }
    }
}

/// Spawn cava and call `on_frame(bars)` for each frame until it returns false.
/// Falls back from pipewire to pulse automatically. Blocks the calling thread.
pub fn run(cfg: &Config, mut on_frame: impl FnMut(&[u8]) -> bool) -> Result<(), String> {
    let mut inputs = vec![cfg.cava_input.clone()];
    for alt in ["pipewire", "pulse"] {
        if !inputs.iter().any(|i| i == alt) {
            inputs.push(alt.to_string());
        }
    }
    let mut last_err = String::new();
    for input in &inputs {
        let started = Instant::now();
        match run_once(cfg, input, &mut on_frame) {
            Ok(_) => return Ok(()),
            Err(e) => {
                eprintln!("[aksara-hud] cava ({input}) gagal: {e}");
                last_err = e;
                // it ran fine for a while and then died: don't hop inputs, just report
                if started.elapsed() > Duration::from_secs(5) {
                    break;
                }
            }
        }
    }
    Err(last_err)
}
